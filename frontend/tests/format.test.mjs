// Склонения, форматы и типограф строк фронтенда (кандидаты W14 и D09). Встроенный тест-раннер Node
// без зависимостей: Node 23.6 и новее импортирует .ts со снятием типов. Запуск: npm --prefix app/frontend test
import assert from 'node:assert/strict';
import { test } from 'node:test';
import { charsGenitive, formatCounter, formatDuration, formatLimitNotice, NBSP, plural, typo } from '../src/format.ts';

const MATERIAL = { one: 'материал', few: 'материала', many: 'материалов' };
/** Неразрывные пробелы видны в сообщении об ошибке: ⍽ вместо U+00A0 */
const show = (text) => text.replaceAll(NBSP, '⍽');
const nb = (text) => text.replaceAll('⍽', NBSP);

test('plural: формы по Intl.PluralRules("ru") для 1, 2, 5, 11, 21, 101', () => {
  const cases = [
    [0, 'материалов'],
    [1, 'материал'],
    [2, 'материала'],
    [4, 'материала'],
    [5, 'материалов'],
    [11, 'материалов'],
    [12, 'материалов'],
    [14, 'материалов'],
    [21, 'материал'],
    [22, 'материала'],
    [25, 'материалов'],
    [101, 'материал'],
    [111, 'материалов'],
  ];
  for (const [n, word] of cases) assert.equal(plural(n, MATERIAL), word, `n = ${n}`);
});

test('plural: дробное число берёт форму other, по умолчанию few', () => {
  assert.equal(plural(1.5, MATERIAL), 'материала');
  assert.equal(plural(1.5, { ...MATERIAL, other: 'материала*' }), 'материала*');
});

test('счётчик поля: родительный падеж после «из N» и «до N», число не отрывается от слова', () => {
  assert.equal(charsGenitive(1), 'символа');
  assert.equal(charsGenitive(2), 'символов');
  assert.equal(charsGenitive(5), 'символов');
  assert.equal(charsGenitive(11), 'символов');
  assert.equal(charsGenitive(21), 'символа');
  assert.equal(charsGenitive(101), 'символа');
  assert.equal(charsGenitive(300), 'символов');
  assert.equal(show(formatCounter(12, 300)), '12⍽из 300⍽символов');
  assert.equal(show(formatCounter(5, 21)), '5⍽из 21⍽символа');
});

test('длительность: минуты, ровные часы, часы с минутами; число и единица не разрываются', () => {
  assert.equal(show(formatDuration(15)), '15⍽мин');
  assert.equal(show(formatDuration(119)), '119⍽мин');
  assert.equal(show(formatDuration(120)), '2⍽ч');
  assert.equal(show(formatDuration(150)), '2⍽ч 30⍽мин');
  assert.equal(formatDuration(0), null);
  assert.equal(formatDuration(null), null);
});

test('типограф: однобуквенные слова, тире, число и слово, диапазоны', () => {
  const cases = [
    ['Подходит для стадии «недавно начали» и сферы «кафе и рестораны»', 'Подходит для стадии «недавно начали» и⍽сферы «кафе и⍽рестораны»'],
    ['Вы начали этот курс — продолжите с текущего урока', 'Вы начали этот курс⍽— продолжите с⍽текущего урока'],
    ['Займёт около 15 минут', 'Займёт около 15⍽минут'],
    ['Вебинар: таргетированная реклама с бюджетом до 10 тысяч', 'Вебинар: таргетированная реклама с⍽бюджетом до 10⍽тысяч'],
    ['Пройдите 10-15 пунктов', 'Пройдите 10–15⍽пунктов'],
    ['Шаги 3—5', 'Шаги 3–5'],
    // Тире с пробелами между числами — знак предложения, а не диапазон: смысл фразы не меняется
    ['Шаги 3 — 5', 'Шаги 3⍽— 5'],
    ['Шаг 1 — 2 часа на настройку', 'Шаг 1⍽— 2⍽часа на настройку'],
    ['День 1 — 3 материала', 'День 1⍽— 3⍽материала'],
    ['Шаг 1 - 2 часа', 'Шаг 1⍽— 2⍽часа'],
    ['В задаче и в истории', 'В⍽задаче и⍽в⍽истории'],
    ['Сравнение готово - изменились позиции', 'Сравнение готово⍽— изменились позиции'],
    ['Рост 5 % за квартал', 'Рост 5⍽% за квартал'],
    ['Документ № 7', 'Документ №⍽7'],
    ['«А также» (в начале)', '«А⍽также» (в⍽начале)'],
    ['Версия 2026-11-12 и телефон 8-800-555', 'Версия 2026-11-12⍽и⍽телефон 8-800-555'],
  ];
  for (const [input, expected] of cases) assert.equal(show(typo(input)), expected, input);
});

test('типограф: повторный вызов результат не меняет, пустая строка и текст без правил остаются как есть', () => {
  for (const text of ['Подходит для стадии «недавно начали» и сферы', 'Пройдите 10-15 пунктов', 'Курс — с нуля', 'Шаг 1 — 2 часа', '']) {
    assert.equal(typo(typo(text)), typo(text), text);
  }
  assert.equal(typo('Подобрать материалы'), 'Подобрать материалы');
  assert.equal(typo('Сравнение готово. Подбор по теме не нашёл материалов по запросу.'), 'Сравнение готово. Подбор по теме не нашёл материалов по запросу.');
});

test('предел поля: при наборе — предел, при вставке — на сколько длиннее, падеж после «на N»', () => {
  assert.equal(show(formatLimitNotice(300, 0)), 'Это предел. Поле вмещает 300⍽символов.');
  assert.equal(show(formatLimitNotice(300, 1)), 'Вставка длиннее на 1⍽символ, её конец не поместился. Поле вмещает 300⍽символов.');
  assert.equal(show(formatLimitNotice(300, 3)), 'Вставка длиннее на 3⍽символа, её конец не поместился. Поле вмещает 300⍽символов.');
  assert.equal(show(formatLimitNotice(300, 20)), 'Вставка длиннее на 20⍽символов, её конец не поместился. Поле вмещает 300⍽символов.');
  assert.equal(show(formatLimitNotice(21, 21)), 'Вставка длиннее на 21⍽символ, её конец не поместился. Поле вмещает 21⍽символа.');
  assert.equal(formatLimitNotice(300, 0), nb('Это предел. Поле вмещает 300⍽символов.'));
});
